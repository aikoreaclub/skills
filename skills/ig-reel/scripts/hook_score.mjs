#!/usr/bin/env node
// 릴스·쇼츠 대본 검사기 v2 (2026-11-09 재보정)
// 점수는 두 자료에 맞췄고, 항목마다 근거를 표시한다.
//  [우리 92편] 밤샘AI 인스타 릴스 92편(2026-09-29~11-09)의 대본과 조회·저장. 조회는 앞뒤 7일 다른 편의 중앙과 비교한 '배수', 저장은 도달 1,000회당.
//  [외부 82편] 조회 50만 넘은 한국어 AI·업무 쇼츠 82편(업무 꿀팁 채널이 많다). 첫 문장 유형·길이·말 속도.
// v1 은 외부 자료의 '첫 문장 유형'에 무게를 실었는데 우리 릴스에 돌려 보니 점수와 조회가 따로 놀았다(순위상관 0.09). v2 는 우리 편에서 실제로 차이가 난 항목(한 사람이 주인공, 결과 먼저, 근데 두 번, 따라 할 한 줄)에 무게를 싣는다.
// 표본이 작다. 점수는 보장이 아니다.
// 사용: node hook_score.mjs 대본.txt [--sec 40]   (한 줄 = 한 장면, 첫 줄이 첫 문장)
import fs from "node:fs";
const a = process.argv.slice(2); const si = a.indexOf("--sec"); const sec = si >= 0 ? Number(a[si + 1]) : null;
const file = a.find((x, i) => !x.startsWith("--") && a[i - 1] !== "--sec");
const src = file && file !== "-" ? fs.readFileSync(file, "utf8") : fs.readFileSync(0, "utf8");
const scenes = src.replace(/\r/g, "").split("\n").map((l) => l.trim()).filter(Boolean);
const first = scenes[0] || "", body = scenes.slice(1).join("\n"), all = scenes.join("\n");
const R = []; let score = 100; const hit = (n, p, w, ev) => { R.push({ n, p, w, ev }); score += p; };
const len = (s) => s.replace(/[\s.,!?'"“”‘’…]/g, "").length, fl = len(first);

// 1) 주인공이 한 사람인 첫 문장. [우리 92편] 조회 1.6배 vs 0.92배, 저장 12.3 vs 7.3 (22편)
const PERSON = /(한 사람|한 명|혼자|직장인|회사원|워킹맘|학생|고등학생|대학생|모르는 사람|경력 0|개발자 한|크리에이터 한|엄마|아빠|부부|사장님|알바)/;
if (PERSON.test(first)) hit("주인공", 0, "첫 문장에 한 사람이 있다", "우리 92편: 조회 1.6배 vs 0.92배, 저장/천 12.3 vs 7.3");
else if (PERSON.test(scenes.slice(0, 3).join(" "))) hit("주인공", -5, "사람이 둘째·셋째 장면에야 나온다. 첫 문장으로 올리기", "우리 92편: 첫 문장에 한 사람이 있는 편 1.6배");
else hit("주인공", -12, `누가 한 일인지가 없다. 회사·기능이 아니라 한 사람을 첫 문장에("코딩 경력 0인 직장인이, 퇴근 뒤 12시간에 만든 게임입니다")`, "우리 92편: 첫 문장에 한 사람이 있는 편 조회 1.6배 vs 없는 편 0.92배");
// 2) 결과 먼저. [우리 92편] 조회 1.16 vs 0.98, 저장 11.7 vs 5.9 (29편)
if (/(만든|만들었|벌|받았|이겼|바꿨|끝냈|통과|뚫렸|가져왔)/.test(first)) hit("결과 먼저", 0, "첫 문장에 결과가 있다", "우리 92편: 조회 1.16배 vs 0.98배, 저장/천 11.7 vs 5.9");
else hit("결과 먼저", -6, "첫 문장에 '무엇이 됐는지'가 없다. 만든 것·번 것·이긴 것부터", "우리 92편: 결과 먼저 편 저장/천 11.7 vs 5.9");
// 3) 그런데·근데 2번 이상. [우리 92편] 조회 1.17 vs 0.91, 저장 10.3 vs 6.2
const turns = (body.match(/(그런데|근데|하지만)/g) || []).length;
if (turns >= 2) hit("뒤집기", 0, `그런데·근데 ${turns}번`, "우리 92편: 2번 이상 편 조회 1.17배 vs 0.91배, 저장/천 10.3 vs 6.2");
else hit("뒤집기", turns ? -6 : -12, `그런데·근데 ${turns}번. 사건 → 더 큰 문제 → 내 일로 두 번은 뒤집기`, "우리 92편: 2번 이상 1.17배 vs 0.91배");
// 4) 따라 할 한 줄. [우리 92편] 조회는 차이 없음(0.96 vs 1.01), 저장 9.5 vs 5.9
if (/(치면|입력하면|누르면|설정에서|메뉴에서|저장해 두|이렇게 치|이 문장|이 한 줄|복사)/.test(body)) hit("따라 할 한 줄", 0, "복사할 문장·설정 경로 있음", "우리 92편: 저장/천 9.5 vs 5.9 (조회는 차이 없음)");
else hit("따라 할 한 줄", -8, "따라 할 한 줄이 없다. 끝에서 세 번째 장면에 2초 이상 고정", "우리 92편: 있는 편 저장/천 9.5 vs 없는 편 5.9");
// 5) 소재가 '사람이 뭔가 해낸 이야기'인가. [우리 92편] 조회 1.25 vs 0.85, 저장 10.6 vs 4.7
if (/(만들었|만든 사람|혼자 만|독학|해냈|이겼|바꿨)/.test(all)) hit("소재", 0, "누군가 해낸 이야기", "우리 92편: 조회 1.25배 vs 0.85배, 저장/천 10.6 vs 4.7");
else hit("소재", -6, "기능·소식 설명형. 그 기능으로 뭔가 해낸 사람이 있으면 그 사람 이야기로", "우리 92편: 사람이 해낸 이야기 1.25배 vs 기능·소식 0.85배");
// 6) 첫 문장 길이. [우리 92편] 20자 이하가 더 좋지 않았다(0.85 vs 1.01). 너무 길 때만 본다
if (fl > 45) hit("첫 문장 길이", -5, `${fl}자. 한 숨에 읽히게 45자 안으로`, "참고");
else hit("첫 문장 길이", 0, `${fl}자`, "우리 92편: 20자 이하로 줄여도 조회는 안 올랐다");

// ── 참고(외부 82편에만 근거. 업무 꿀팁 채널 기준이라 소재가 다르면 안 맞을 수 있다) ──
let kind = null;
if (/(모르면|숨은|숨겨|아직도|손해|몰랐)/.test(first)) kind = ["숨은 기능·모르면 손해", 321];
else if (/(셨죠|없으세요|계셨나요|하시죠|분들은|어려우|귀찮|막막)/.test(first)) kind = ["문제 상황 공감", 282];
else if (/\?$/.test(first)) kind = ["질문", 191];
else if (/(드디어|나왔|출시|공개|발표)/.test(first)) kind = ["새 소식 선언", 169];
else if (/(만든|만들었|풀어봤|해 봤|시켰더니)/.test(first)) kind = ["결과·시연 먼저", 158];
if (kind) hit("첫 문장 유형", 0, `${kind[0]}`, `외부 82편: 이 유형 조회 중앙 ${kind[1]}만(업무 꿀팁 채널 기준, 참고)`);
const andCount = (body.match(/그리고/g) || []).length; if (andCount >= 2) hit("나열", -3, `"그리고" ${andCount}번`, "이야기 규칙(참고) · 우리 92편에선 차이 없음");
const last = scenes[scenes.length - 1] || ""; if (/\?$/.test(last)) hit("끝", -3, "질문으로 끝남. 반전 한 줄이 낫다", "이야기 규칙(참고) · 우리 편은 거의 다 반전 끝이라 비교 자료 없음");
if (/^(오늘은|안녕하세요|이번 영상|이번 시간)/.test(first)) hit("인사·예고", -10, "\"오늘은 ○○에 대해 알아보겠습니다\"로 여는 첫 문장", "외부 82편: 말 있는 60편 중 이렇게 여는 편 0, 0.5초 안에 본론 93%");
const JARGON = ["프롬프트", "에이전트", "토큰", "API", "MCP", "파인튜닝", "벡터", "RAG", "LLM", "오픈소스", "깃허브", "벤치마크", "파라미터", "컨텍스트", "임베딩", "멀티모달", "플러그인", "터미널", "온디바이스", "양자화", "가중치"];
const found = JARGON.filter((w) => src.includes(w)); if (found.length >= 2) hit("낯선 말", -4, `${found.join("·")}. 하나만 남기고 풀어 쓰기`, "이해 검사 규칙(참고)");
const total = scenes.reduce((s, l) => s + len(l), 0);
if (sec) { const cps = +(total / sec).toFixed(1); if (sec > 60) hit("길이", -6, `${sec}초`, "외부 82편: 60초 초과 조회 중앙 118만 vs 30~60초 227~237만(참고)"); else hit("길이", 0, `${sec}초`, "외부 82편: 30~60초"); if (cps < 6) hit("말 속도", -4, `초당 ${cps}자`, "외부 82편: 터진 편 초당 7.6자(참고)"); else hit("말 속도", 0, `초당 ${cps}자`, "외부 82편: 7.6자"); }
if (/(충격|경악|꼭 보세요|실화)/.test(src)) hit("과장", -4, "충격·경악·꼭 보세요", "규칙");
if (/[一-鿿]/.test(src)) hit("한자", -30, "한자 금지", "규칙");
score = Math.max(0, Math.min(100, score));
console.log(`릴스·쇼츠 대본 검사  ${score}점 — ${score >= 85 ? "찍어도 됨" : score >= 65 ? "표시된 곳 손보기" : "다시 쓰기"}\n`);
for (const r of R) console.log(`${r.p < 0 ? "▼" : "·"} ${r.n} ${r.p ? `(${r.p}) ` : ""}${r.w}\n    근거: ${r.ev}`);
console.log(`\n첫 문장: ${first}`);
console.log(`점수는 우리 릴스 92편과 외부 쇼츠 82편에 맞춘 값이에요. 표본이 작아 보장이 아니에요.`);
console.log(JSON.stringify({ score, kind: kind ? kind[0] : null, firstLen: fl, scenes: scenes.length, chars: total, sec, turns, issues: R.filter((r) => r.p < 0).map((r) => r.n) }));
