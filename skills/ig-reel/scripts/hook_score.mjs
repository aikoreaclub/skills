#!/usr/bin/env node
// 릴스·쇼츠 대본 검사기 v3 (2026-11-09, 우리 자료 + 외부 자료 결합)
// 근거 자료 둘. 항목마다 어느 쪽에서 확인됐는지 표시한다.
//  [우리 138편] 우리 세 계정(밤샘AI·jejeAI·AIKC) 인스타 릴스 138편의 대본·조회·저장. 조회는 같은 계정 앞뒤 7일 편의 중앙 대비 '배수', 저장은 도달 1,000회당.
//  [외부 쇼츠] 한국 AI·업무·IT 유튜브 채널 23곳에서 채널마다 잘 된 편·안 된 편을 골라 자막을 읽은 228편(잘 된 120 · 안 된 108). 구독자 차이를 거르려고 그 채널 쇼츠 조회 중앙 대비로 잘 됨·안 됨을 나눴다.
// 무게: 양쪽에서 같은 방향으로 나온 항목이 가장 크다. 한쪽에만 나온 항목은 그 유형(성공담형 / 꿀팁·설명형)일 때만 적용한다.
// 표본이 작다. 점수는 보장이 아니다.
// 사용: node hook_score.mjs 대본.txt [--sec 40]   (한 줄 = 한 장면, 첫 줄이 첫 문장)
import fs from "node:fs";
const a = process.argv.slice(2); const si = a.indexOf("--sec"); const sec = si >= 0 ? Number(a[si + 1]) : null;
const file = a.find((x, i) => !x.startsWith("--") && a[i - 1] !== "--sec");
const src = file && file !== "-" ? fs.readFileSync(file, "utf8") : fs.readFileSync(0, "utf8");
const scenes = src.replace(/\r/g, "").split("\n").map((l) => l.trim()).filter(Boolean);
const first = scenes[0] || "", first2 = scenes.slice(0, 2).join(" "), body = scenes.slice(1).join("\n"), all = scenes.join("\n");
const R = []; let score = 100; const hit = (n, p, w, ev) => { R.push({ n, p, w, ev }); score += p; };
const len = (s) => s.replace(/[\s.,!?'"“”‘’…]/g, "").length, fl = len(first);

// ── 양쪽 자료에서 모두 확인된 것 ──
// 1) 그런데·근데·하지만 2번 이상
const turns = (body.match(/(그런데|근데|하지만)/g) || []).length;
if (turns >= 2) hit("뒤집기", 0, `그런데·근데 ${turns}번`, "우리 138편: 1.1배·저장 8.2 vs 0.94배·저장 3.3 / 외부 쇼츠: 잘 된 편 17.5% vs 안 된 편 8.3%");
else hit("뒤집기", turns ? -6 : -12, `그런데·근데 ${turns}번. 사건 → 더 큰 문제 → 내 일로 두 번은 뒤집기`, "우리 138편: 2번 이상 편 저장 8.2 vs 3.3 / 외부 쇼츠: 잘 된 편 17.5% vs 안 된 편 8.3%");
// 2) 첫 문장 41자 이상
if (fl >= 41) hit("첫 문장 길이", -8, `${fl}자. 40자 안으로`, "우리 138편: 41자 이상 0.88배·저장 0.9 vs 4.4 / 외부 쇼츠: 잘 된 편 21.7% vs 안 된 편 30.6%");
else hit("첫 문장 길이", 0, `${fl}자`, "양쪽 자료: 41자 이상이 손해");
// 3) 1인칭으로 여는 첫 두 문장
if (/(제가|저는|저도|나는|내가)/.test(first2)) hit("1인칭 시작", -6, "\"제가·저는\"으로 연다. 보는 사람이나 주인공을 앞에", "우리 138편: 0.9배·저장 0.8 vs 4.7 / 외부 쇼츠: 잘 된 편 16.7% vs 안 된 편 25.9%");
// 4) 따라 할 한 줄
if (/(치면|입력하면|누르면|누르고|클릭|설정에서|메뉴에서|저장해 두|이렇게 치|이 문장|이 한 줄|복사)/.test(body)) hit("따라 할 한 줄", 0, "복사할 문장·누를 곳 있음", "우리 138편: 저장 9.0 vs 1.1(조회는 차이 없음) / 외부 쇼츠: 잘 된 편 21.7% vs 안 된 편 16.7%");
else hit("따라 할 한 줄", -8, "따라 할 한 줄이 없다. 끝에서 세 번째 장면에 2초 이상 고정", "우리 138편: 있는 편 저장 9.0 vs 없는 편 1.1 / 외부 쇼츠: 잘 된 편 21.7% vs 안 된 편 16.7%");

// ── 유형에 따라 다른 것 ──
const PERSON = /(한 사람|한 명|혼자|직장인|회사원|워킹맘|학생|고등학생|대학생|모르는 사람|경력 0|개발자 한|크리에이터 한|엄마|아빠|부부|사장님|알바)/;
const story = PERSON.test(scenes.slice(0, 3).join(" ")) || /(만들었|만든 사람|혼자 만|독학|해냈|이겼)/.test(all);
if (story) {
  // 성공담형(누군가 해낸 이야기): 우리 세 계정 자료에서만 확인. 외부 채널은 이 유형이 드물어(3% 안팎) 비교하지 못했다.
  hit("유형", 0, "성공담형(누군가 해낸 이야기)", "우리 138편: 이 유형 1.2배·저장 9.3 vs 0.92배·저장 1.4");
  if (PERSON.test(first)) hit("주인공", 0, "첫 문장에 한 사람이 있다", "우리 138편: 1.24배·저장 8.7 vs 0.97배·저장 3.4");
  else hit("주인공", -6, "사람이 첫 문장에 없다. 회사·기능이 아니라 한 사람을 맨 앞에", "우리 138편: 첫 문장에 한 사람이 있는 편 1.24배·저장 8.7 vs 3.4");
  if (/(만든|만들었|벌|받았|이겼|바꿨|끝냈|통과|가져왔)/.test(first)) hit("결과 먼저", 0, "첫 문장에 결과가 있다", "우리 138편: 저장 9.4 vs 3.3");
  else hit("결과 먼저", -4, "첫 문장에 '무엇이 됐는지'가 없다", "우리 138편: 결과가 있는 첫 문장 저장 9.4 vs 3.3");
} else {
  // 꿀팁·설명형: 외부 쇼츠에서 확인. 우리 계정엔 이 유형의 좋은 표본이 적다.
  hit("유형", -4, "꿀팁·설명형. 그 기능으로 뭔가 해낸 사람이 있으면 그 사람 이야기로 바꾸는 편이 낫다", "우리 138편: 성공담형이 아닌 편 0.92배·저장 1.4");
  if (/(이거|이렇게|이런|여기|이 버튼|이 화면|보시면)/.test(first)) hit("화면 가리키기", 0, "첫 문장이 화면 속 실물을 가리킨다", "외부 쇼츠: 잘 된 편 26.7% vs 안 된 편 16.7%");
  else hit("화면 가리키기", -6, "첫 문장이 화면을 가리키지 않는다(\"이거·이렇게·여기\")", "외부 쇼츠: 잘 된 편 26.7% vs 안 된 편 16.7%");
  if (fl > 20) hit("첫 문장 짧게", -3, `${fl}자. 꿀팁형은 20자 안쪽이 유리했다`, "외부 쇼츠: 20자 이하가 잘 된 편 38.3% vs 안 된 편 28.7% (우리 자료에선 차이 없음)");
}
// 질문으로 여는 첫 문장: 우리 자료에서 손해, 외부는 차이 없음
if (/\?/.test(first)) hit("질문 첫 문장", -4, "질문으로 연다", "우리 138편: 0.86배·저장 1.6 vs 5.4 / 외부 쇼츠: 차이 없음(13.3% vs 11.1%)");

// ── 근거가 없거나 약해 점수에 넣지 않는 것(알림만) ──
if (/^(오늘은|안녕하세요|이번 영상|이번 시간)/.test(first)) hit("인사·예고", 0, "\"오늘은 ○○…\"으로 연다. 자료로는 손해가 확인되지 않았다", "외부 쇼츠: 잘 된 편 7.5% vs 안 된 편 2.8%(표본 작음)");
const last = scenes[scenes.length - 1] || ""; if (/\?$/.test(last)) hit("질문 끝", 0, "질문으로 끝남", "근거 자료 부족(외부 쇼츠 4.2% vs 1.9%)");
const total = scenes.reduce((s, l) => s + len(l), 0);
if (sec) hit("길이", 0, `${sec}초 · 초당 ${(total / sec).toFixed(1)}자`, "외부 쇼츠: 대본 길이별 차이 없음");
// 규칙 점검
const JARGON = ["프롬프트", "에이전트", "토큰", "API", "MCP", "파인튜닝", "벡터", "RAG", "LLM", "오픈소스", "깃허브", "벤치마크", "파라미터", "컨텍스트", "임베딩", "멀티모달", "플러그인", "터미널", "온디바이스", "양자화", "가중치"];
const found = JARGON.filter((w) => src.includes(w)); if (found.length >= 2) hit("낯선 말", -4, `${found.join("·")}. 하나만 남기고 풀어 쓰기`, "이해 규칙(성과 근거 없음)");
if (/[一-鿿]/.test(src)) hit("한자", -30, "한자 금지", "규칙");
score = Math.max(0, Math.min(100, score));
console.log(`릴스·쇼츠 대본 검사  ${score}점 — ${score >= 85 ? "찍어도 됨" : score >= 65 ? "표시된 곳 손보기" : "다시 쓰기"}\n`);
for (const r of R) console.log(`${r.p < 0 ? "▼" : "·"} ${r.n} ${r.p ? `(${r.p}) ` : ""}${r.w}\n    근거: ${r.ev}`);
console.log(`\n첫 문장: ${first}`);
console.log(`점수는 우리 릴스 138편과 외부 쇼츠 228편에 맞춘 값이에요. 표본이 작아 보장이 아니에요.`);
console.log(JSON.stringify({ score, type: story ? "성공담형" : "꿀팁·설명형", firstLen: fl, scenes: scenes.length, chars: total, sec, turns, issues: R.filter((r) => r.p < 0).map((r) => r.n) }));
