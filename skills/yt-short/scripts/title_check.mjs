#!/usr/bin/env node
// 유튜브 쇼츠 제목 검사기 v2 (2026-11-09 외부 자료로 재보정)
// 근거: [외부 2,314편] 한국 AI·업무·IT 채널 23곳의 쇼츠 2,314편. 각 편의 조회를 그 채널 쇼츠 조회 중앙과 비교한 '배수'로 봤다(구독자 차이를 거르려고).
// 먼저 알아 둘 것: 쇼츠 제목은 조회에 주는 영향이 작다. 어떤 제목 특징도 배수 1.2를 넘지 못했고(가장 큰 것이 따옴표 인용 1.2, 숫자 1.12), v1 의 "질문형·큰 의미" 점수는 조회와 관계가 없었다(순위상관 0.03).
// 그래서 이 검사기는 '조회를 올리는 제목'을 찾는 도구가 아니라, 손해 보는 제목(너무 긴 제목 등)을 걸러 내고 여러 안을 나란히 보는 도구다. 조회는 첫 문장과 내용이 정한다(ig-reel 스킬).
// 사용: node title_check.mjs "제목" ["제목2" ...]
const titles = process.argv.slice(2).filter(Boolean); if (!titles.length) { console.error('사용: node title_check.mjs "제목" ["제목2"]'); process.exit(1); }
const HARD = ["난제", "비공개", "탐지기", "선언문", "에이전트", "프롬프트", "토큰", "API", "벤치마크", "파라미터", "추론", "멀티모달", "오픈소스", "온디바이스", "생태계", "로드맵", "패러다임", "거버넌스", "레거시", "아키텍처", "인프라"];
const rows = titles.map((t) => {
  const n = t.replace(/\s/g, "").length; const R = []; let s = 80; const hit = (k, p, w, ev) => { R.push({ k, p, w, ev }); s += p; };
  // 손해가 확인된 것
  if (n >= 31) hit("길이", -12, `${n}자. 30자 안으로`, "외부 2,314편: 31자 이상 0.82배(192편)");
  else hit("길이", 0, `${n}자`, "외부 2,314편: 12자 이하·13~20자·21~30자는 차이 없음(1.0·1.0·1.04)");
  if (/(만원|억|무료|공짜|가격|\d원|월급|연봉)/.test(t)) hit("돈 표현", -6, "돈·가격을 앞세운 제목", "외부 2,314편: 0.83배(77편)");
  if (/(하세요|마세요|해라|하지 마|보세요|쓰세요)/.test(t)) hit("명령형", -3, "~하세요·~마세요", "외부 2,314편: 0.93배(80편)");
  // 조금 유리했던 것(크지 않다)
  if (/["'“‘「]/.test(t)) hit("따옴표 인용", +8, "누군가의 말·화면 속 문장을 그대로", "외부 2,314편: 1.2배(115편)");
  if (/\d/.test(t)) hit("숫자", +5, "숫자 있음", "외부 2,314편: 1.12배(563편)");
  if (/(vs|VS|비교|차이)/.test(t)) hit("비교", +5, "vs·비교·차이", "외부 2,314편: 1.12배(55편)");
  if (/(이유|진짜|사실|정체|비밀|근황)/.test(t)) hit("이유·진짜", +3, "이유·진짜·사실·정체", "외부 2,314편: 1.08배(259편)");
  if (/(직장인|개발자|사람|신입|사장|엄마|아빠|학생|회사원|교수|의사|대표)/.test(t)) hit("사람", +2, "사람이 보임", "외부 2,314편: 1.06배(150편)");
  // 차이가 없던 것(점수 없음, 알림만)
  if (/\?/.test(t)) hit("물음표", 0, "질문형은 유리하지 않았다", "외부 2,314편: 0.94배(429편)");
  if (/(ㄷㄷ|미친|미쳤|대박|충격|실화|소름|난리|역대급|레전드)/.test(t)) hit("감탄", 0, "감탄·과장 단어는 조회에 차이가 없었다. 계정 말투 규칙에 맞는지만 보기", "외부 2,314편: 1.03배(174편)");
  // 규칙 점검(성과 근거 없음)
  const hard = HARD.filter((w) => t.includes(w)); if (hard.length) hit("어려운 말", -4, `${hard.join("·")} — 쉬운 말로`, "이해 규칙(성과 근거 없음)");
  if (/#shorts|【|】/i.test(t)) hit("군더더기", -3, "#shorts·【】", "규칙");
  if (/[一-鿿]/.test(t)) hit("한자", -30, "한자 금지", "규칙");
  return { t, n, s: Math.max(0, Math.min(100, s)), R };
});
rows.sort((a, b) => b.s - a.s);
for (const r of rows) { console.log(`${String(r.s).padStart(3)}점  ${r.t}`); for (const x of r.R) console.log(`       ${x.p < 0 ? "▼" : x.p > 0 ? "▲" : "·"} ${x.k}${x.p ? ` (${x.p > 0 ? "+" : ""}${x.p})` : ""} ${x.w}  [${x.ev}]`); }
console.log(`\n쇼츠 제목은 조회에 주는 영향이 작아요(외부 2,314편에서 어떤 제목 특징도 1.2배를 못 넘음). 손해 보는 제목만 피하고, 힘은 첫 문장에 쓰세요.`);
console.log(JSON.stringify(rows.map((r) => ({ title: r.t, score: r.s, chars: r.n, issues: r.R.filter((x) => x.p < 0).map((x) => x.k), plus: r.R.filter((x) => x.p > 0).map((x) => x.k) }))));
