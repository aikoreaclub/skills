#!/usr/bin/env node
// 쓰레드 글 검사기 v2 (2026-11-09 재보정)
// 점수는 두 자료에 맞췄다. 항목마다 어느 자료가 근거인지 표시한다.
//  [우리 93편] 밤샘AI 쓰레드 글 93편(2026-10-01~11-09). 계정 조회가 시기에 따라 크게 달라서, 각 글을 앞뒤 7일 다른 글의 조회 중앙과 비교한 '배수'로 봤다.
//  [외부 49편] 한국어 AI·IT·직장 쓰레드 바이럴 49편(조회 4만+ 16편 vs 1천 미만 12편). 계정이 달라 팔로워 차이는 못 걸렀다.
// v1 은 외부 자료만으로 감점을 크게 줬는데 우리 글에 돌려 보니 점수와 조회가 따로 놀았다(순위상관 0.05). v2 는 우리 글에서 실제로 차이가 난 항목에 무게를 싣고, 외부 자료만 있는 항목은 '참고'로 작게 준다.
// 표본이 작다. 점수는 보장이 아니라 "지금까지 자료로 본 확률"이다.
// 사용: node th_check.mjs 글.txt   또는   cat 글.txt | node th_check.mjs      의존성·네트워크 없음.
import fs from "node:fs";
const src = process.argv[2] && process.argv[2] !== "-" ? fs.readFileSync(process.argv[2], "utf8") : fs.readFileSync(0, "utf8");
const lines = src.replace(/\r/g, "").split("\n").map((l) => l.trimEnd());
const body = lines.filter((l) => !/^(출처|원문|원글|링크)\s/.test(l) && !/https?:\/\//.test(l));
const text = body.join("\n"), nonEmpty = body.filter((l) => l.trim()), first = nonEmpty[0] || "";
const len = (s) => s.replace(/\s/g, "").length, noSpace = len(text), fl = len(first);
const R = []; let score = 100; const hit = (name, pts, why, ev) => { R.push({ name, pts, why, ev }); score += pts; };

// ── 첫 줄 ──
// 1) 내 것 확인형: 대상(기기·계정·직업) + 지금 내 것에 생긴 일. [우리 93편] 해당 4편 배수 중앙 7.1(나머지 0.97), 계정 1위 17,682회가 이 꼴.
const MINE_T = /(윈도우|아이폰|갤럭시|맥북|컴퓨터|노트북|폰|계정|카톡|카카오톡|인스타|유튜브|챗GPT|클로드|제미나이|엑셀|메일|통장|카드|직장인|회사원|사장님|자영업|취준생|대학생|부모|쓰는 사람|쓰는 분)/;
const MINE_E = /(끊긴|끊겼|끊김|막을|막힘|막혔|막는|바뀌|바뀐|사라|없어[지졌]|털렸|유출|새고|꺼[져졌]|켜[져졌]|오른|내린|확인|해당|대상)/;
const mine = MINE_T.test(first) && MINE_E.test(first);
// 2) 아는 이름: [우리 93편] 있고 없고 차이 없음(1.07 vs 1.09). 단, 상위 3편은 모두 아는 이름 + 뜻밖의 작은 쪽. 꼴 표시만 한다.
const FAMOUS = /(올트먼|머스크|저커버그|놀란|젠슨|오픈AI|구글|애플|삼성|네이버|카카오|챗GPT|클로드|제미나이|엔비디아|마이크로소프트|메타|테슬라|아마존|넷플릭스|디즈니|유튜브|인스타|틱톡|윈도우|아이폰|갤럭시|할리우드|GTA|폴아웃|스타크래프트|고질라|포켓몬|마인크래프트|닌텐도|픽사|지브리)/;
const SMALL = /(한 사람|한 명|혼자|집 컴퓨터|노트북 한 대|공짜|무료로|며칠|하루 만에|주말에|워킹맘|고등학생|안 본대|안 쓴대)/;
const kinds = [];
if (mine) kinds.push("내 것 확인");
if (FAMOUS.test(first) && SMALL.test(first)) kinds.push("아는 이름 vs 한 사람");
if (/(하지 ?마|치지 ?마|라고만|잘못 쓰고|아직도|그렇게 쓰면|사실 .*아님|가 아님)/.test(first)) kinds.push("바로잡기");
if (/(했더니|해 봤더니|해보니|써 봤더니|시켜 봤더니)/.test(first)) kinds.push("해 봤더니");
if (/( vs |둘 중|파 vs)/.test(first)) kinds.push("비교·투표");
if (mine) hit("첫 줄 꼴", 0, "내 것 확인형(대상 + 지금 내 것에 생긴 일). 지금까지 가장 센 꼴", "우리 93편: 해당 4편 배수 중앙 7.1 vs 나머지 0.97");
else if (kinds.length) hit("첫 줄 꼴", 0, kinds.join("+"), "외부 49편: 4만+ 글 16편이 모두 이 꼴들 중 하나");
else if (/(출시|공개했|발표했|업데이트했|선보였|도입했)/.test(first)) hit("첫 줄 꼴", -8, `소식을 알리는 첫 줄. 읽는 사람의 기기·계정·일에 지금 생긴 일로 바꿔 보기("윈도우 11인데 10월 13일부터 보안 업데이트가 끊긴 컴퓨터가 있음")`, "외부 49편: 4만+ 16편 중 0편 / 우리 93편에선 차이 확인 안 됨(참고)");
else hit("첫 줄 꼴", -4, "꼴이 안 잡힌다. 읽는 사람의 것(기기·계정·일)에 지금 생긴 일이 있으면 그걸 첫 줄로", "참고");
// 3) 첫 줄 길이: [우리 93편] 30자 이하 배수 중앙 1.32 vs 넘는 글 0.78
if (fl > 30) hit("첫 줄 길이", fl > 40 ? -14 : -10, `${fl}자. 30자 안으로 줄이기`, "우리 93편: 30자 이하 1.32배 vs 초과 0.78배");
else hit("첫 줄 길이", 0, `${fl}자`, "우리 93편: 30자 이하 1.32배");
// 4) 첫 줄 말끝: [우리 93편] ~음/~임/~함/~대로 끝난 첫 줄 1.33 vs 0.78
if (/(음|임|함|됨|대|래|듦|봄|큼)[.!]?$/.test(first.trim())) hit("첫 줄 말끝", 0, "~음·~임·~대", "우리 93편: 1.33배 vs 0.78배");
else if (/(습니다|입니다|해요|어요|아요|예요|이에요|했다|한다|됐다)[.!]?$/.test(first.trim())) hit("첫 줄 말끝", -8, "서술문으로 끝난 첫 줄. ~음·~임·~대 로 끊어 보기", "우리 93편: ~음·~임·~대 1.33배 vs 나머지 0.78배");
else hit("첫 줄 말끝", -3, "명사·기타로 끝남", "우리 93편: ~음·~임·~대 가 1.33배");

// ── 본문 ──
// 5) 반전 한 줄: [우리 93편] 있는 글 1.25 vs 없는 글 0.82
if (/(근데|반전은|알고 보니|사실은|그런데)/.test(text)) hit("반전", 0, "뒤집는 줄 있음", "우리 93편: 1.25배 vs 0.82배");
else hit("반전", -12, `중간에 한 번 뒤집는 줄이 없다("근데 댓글 1등은 칭찬이 아니라…")`, "우리 93편: 있는 글 1.25배 vs 없는 글 0.82배");
// 6) 단정 한 줄: [우리 93편] 1.4 vs 0.95(19편), [외부 49편] 4만+ 16편 중 10편
if (/(솔직히|그냥|무조건|절대|결국|사실상|라고 봄|이라고 봄|더 큼|써야 함|하면 됨|쪽$)/m.test(nonEmpty.slice(1).join("\n"))) hit("단정 한 줄", 0, "입장이 있는 줄 있음", "우리 93편: 1.4배 vs 0.95배 · 외부 49편: 10/16");
else hit("단정 한 줄", -12, `입장을 말하는 줄이 없다("솔직히 이건 디자이너보다 회사원한테 더 큼")`, "우리 93편: 있는 글 1.4배 vs 없는 글 0.95배 · 외부 49편: 단정 없던 꿀팁 420회");
// 7) 끝: [우리 93편] 질문·투표로 끝난 글 조회 배수 0.76 vs 아닌 글 1.76. [외부 47편] 판정·투표 요청 글은 답글÷좋아요 0.4 vs 0.06
const last = nonEmpty[nonEmpty.length - 1] || "", asks = /(\?|너넨|너네는|스친들은|몇 번|어느 쪽|대 봐|골라)\s*$/.test(last);
if (asks) hit("끝", -6, "질문·투표로 끝남. 답글은 늘지만 조회는 줄었다. 조회가 목표면 사실이나 할 일 한 줄로 끝내기", "우리 93편: 질문 끝 0.76배 vs 아닌 글 1.76배 / 외부 47편: 답글÷좋아요는 0.4 vs 0.06");
else hit("끝", 0, "질문 없이 끝남", "우리 93편: 1.76배");
// 8) 길이: 쓰레드 한도 500자. [우리 93편] 220자 이하와 그 위는 차이 없음(0.97 vs 1.07). [우리 10월 125편] 280자 넘으면 조회 중앙 87 vs 150~220자 176
if (noSpace > 480) hit("길이", -25, `${noSpace}자. 쓰레드 한도(500자)에 걸린다`, "플랫폼 한도");
else if (noSpace > 280) hit("길이", -6, `${noSpace}자. 280자 아래로`, "우리 10월 125편: 280자 초과 중앙 87 vs 150~220자 176");
else if (noSpace < 60) hit("길이", -6, `${noSpace}자. 반전이나 단정 한 줄이 빠졌을 가능성`, "참고");
else hit("길이", 0, `${noSpace}자(띄어쓰기 뺌)`, "우리 93편: 220자 위아래 차이 없음");

// ── 참고(외부 자료에만 근거가 있고 우리 글에선 차이가 안 난 것, 작게만 감점) ──
const JARGON = ["프롬프트", "에이전트", "토큰", "API", "MCP", "지시문", "파인튜닝", "벡터", "RAG", "LLM", "오픈소스", "깃허브", "레딧", "해커뉴스", "벤치마크", "파라미터", "컨텍스트", "임베딩", "멀티모달", "하네스", "플러그인", "터미널", "CLI", "워크플로", "온디바이스", "양자화", "가중치", "SDK", "토막", "GPU"];
const found = JARGON.filter((w) => text.includes(w));
if (found.length >= 2) hit("낯선 말", -4, `${found.join("·")}. 하나만 남기고 쉬운 말로`, "우리 10월 125편 하위 글 관찰(참고)");
const arrows = (text.match(/→|➡|->/g) || []).length; if (arrows >= 2) hit("단계 나열", -3, `화살표 ${arrows}개. 방법은 답글로 미루기`, "외부 49편(참고) · 우리 93편에선 차이 없음");
if (/(^|\s)#[^\s#]+/.test(src)) hit("해시태그", -3, "본문 해시태그", "외부 49편: 단 5편 중 4편이 120 이하(참고) · 우리 93편에선 차이 없음");
if (/https?:\/\//.test(src)) hit("본문 링크", -5, "링크는 댓글로", "외부 49편: 4만+ 16편 모두 본문 링크 0");
const periods = nonEmpty.filter((l) => /[.。]$/.test(l)).length; if (periods) hit("마침표", -2, `줄 끝 마침표 ${periods}줄`, "말투 규칙(참고)");
if (/(월 ?\d+만 ?원|수익|부업|돈 버는)/.test(text)) hit("수익 표현", -15, "수익·부업 표현", "외부 49편: 부업 글 44~516회 · 계정 안전");
if (/[一-鿿]/.test(src)) hit("한자", -30, "한자 금지", "규칙");

score = Math.max(0, Math.min(100, score));
const grade = score >= 85 ? "올려도 됨" : score >= 65 ? "표시된 곳 손보고 올리기" : "다시 쓰기";
console.log(`쓰레드 글 검사  ${score}점 — ${grade}\n`);
for (const r of R) console.log(`${r.pts < 0 ? "▼" : "·"} ${r.name} ${r.pts ? `(${r.pts}) ` : ""}${r.why}\n    근거: ${r.ev}`);
console.log(`\n첫 줄: ${first}`);
console.log(`점수는 우리 계정 93편과 외부 바이럴 49편에 맞춘 값이에요. 표본이 작아 보장이 아니에요.`);
console.log(JSON.stringify({ score, grade, chars: noSpace, firstLen: fl, lines: nonEmpty.length, firstLine: first, firstKinds: kinds, issues: R.filter((r) => r.pts < 0).map((r) => r.name) }));
