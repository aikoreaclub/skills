#!/usr/bin/env node
// 쓰레드 글 검사기 v3 (2026-11-09, 우리 자료 + 외부 자료 결합)
// 근거 자료 둘. 항목마다 어느 쪽에서 확인됐는지 표시한다.
//  [우리 120편] 우리 세 계정(밤샘AI·jejeAI·AIKC) 쓰레드 글 120편. 조회는 같은 계정 앞뒤 7일 글의 중앙 대비 '배수'.
//  [외부 260편] 한국어 AI·직장·마케팅 쓰레드 계정 20곳의 글 260편(계정당 6편 이상, 올린 지 2일 지난 글). 조회는 그 계정 글의 중앙 대비 '배수'. 로그인 없이 공개 글 페이지에서 읽었다.
// 무게: 양쪽에서 같은 방향으로 나온 항목이 가장 크다. 한쪽에만 나온 항목은 작게, 서로 엇갈린 항목은 점수에 넣지 않고 알리기만 한다.
// 표본이 작다. 점수는 보장이 아니라 "지금까지 자료로 본 확률"이다.
// 사용: node th_check.mjs 글.txt   또는   cat 글.txt | node th_check.mjs      의존성·네트워크 없음.
import fs from "node:fs";
const src = process.argv[2] && process.argv[2] !== "-" ? fs.readFileSync(process.argv[2], "utf8") : fs.readFileSync(0, "utf8");
const lines = src.replace(/\r/g, "").split("\n").map((l) => l.trimEnd());
const body = lines.filter((l) => !/^(출처|원문|원글)\s/.test(l));
const text = body.join("\n"), nonEmpty = body.filter((l) => l.trim()), first = nonEmpty[0] || "";
const len = (s) => s.replace(/\s/g, "").length, noSpace = len(text), fl = len(first);
const R = []; let score = 100; const hit = (name, pts, why, ev) => { R.push({ name, pts, why, ev }); score += pts; };

// ── 양쪽 자료에서 모두 확인된 것 ──
// 1) 단정하는 의견 한 줄
if (/(솔직히|그냥|무조건|절대|결국|사실상|라고 봄|이라고 봄|더 큼|써야 함|하면 됨|쪽$)/m.test(text)) hit("단정 한 줄", 0, "입장이 있는 줄 있음", "우리 120편: 1.35배 vs 1.0배 / 외부 260편: 2.87배 vs 0.99배");
else hit("단정 한 줄", -14, `입장을 말하는 줄이 없다("솔직히 이건 디자이너보다 회사원한테 더 큼")`, "우리 120편: 있는 글 1.35배 vs 1.0배 / 외부 260편: 2.87배 vs 0.99배");
// 2) 중간에 뒤집는 줄
if (/(근데|반전은|알고 보니|사실은|그런데|하지만)/.test(text)) hit("반전", 0, "뒤집는 줄 있음", "우리 120편: 1.25배 vs 0.83배 / 외부 260편: 1.12배 vs 1.0배");
else hit("반전", -10, `중간에 한 번 뒤집는 줄이 없다("근데 댓글 1등은 칭찬이 아니라…")`, "우리 120편: 있는 글 1.25배 vs 없는 글 0.83배 / 외부 260편: 1.12배 vs 1.0배");
// 3) 자세한 것·목록·링크는 답글·댓글로 넘긴다고 예고
if (/(👇|답글에|댓글에|아래에|답글로|댓글로)/.test(text)) hit("답글로 넘기기", 0, "나머지를 답글·댓글로 넘긴다", "우리 120편: 1.25배 vs 1.0배 / 외부 260편: 3.07배 vs 0.94배");
else hit("답글로 넘기기", -8, `본문은 짧게 두고 목록·방법·링크는 "답글에 달아 둠"으로 넘기는 줄이 없다`, "우리 120편: 있는 글 1.25배 vs 1.0배 / 외부 260편: 3.07배 vs 0.94배");
// 4) 내 것 확인형 첫 줄(대상 + 지금 내 것에 생긴 일). 양쪽 모두 높지만 표본이 3편씩이라 가점 없이 꼴만 알린다
const MINE_T = /(윈도우|아이폰|갤럭시|맥북|컴퓨터|노트북|폰|계정|카톡|카카오톡|인스타|유튜브|챗GPT|클로드|제미나이|엑셀|메일|통장|카드|직장인|회사원|사장님|자영업|취준생|대학생|부모|쓰는 사람|쓰는 분)/;
const MINE_E = /(끊긴|끊겼|끊김|막을|막힘|막혔|막는|막음|바뀌|바뀐|바뀜|바꼈|사라|없어[지졌]|털렸|유출|새고|꺼[져졌]|켜[져졌])/;
const mine = MINE_T.test(first) && MINE_E.test(first);
if (mine) hit("첫 줄 꼴", 0, "내 것 확인형(대상 + 지금 내 것에 생긴 일)", "우리 120편: 3편 배수 중앙 5.5 / 외부 260편: 3편 1.7 (양쪽 다 높지만 표본이 작다)");
else hit("첫 줄 꼴", -3, "읽는 사람의 기기·계정·일에 지금 생긴 일이 있으면 그걸 첫 줄로", "우리 120편: 해당 3편 5.5배 / 외부 260편: 3편 1.7배(표본 작음, 참고)");

// ── 한쪽 자료에서만 확인된 것(작게) ──
if (fl > 30) hit("첫 줄 길이", -6, `${fl}자. 30자 안으로`, "우리 120편: 30자 이하 1.25배 vs 0.87배 / 외부 260편: 차이 없음(외부 글은 80%가 이미 30자 이하)");
else hit("첫 줄 길이", 0, `${fl}자`, "우리 120편: 30자 이하 1.25배");
if (/https?:\/\//.test(text)) hit("본문 링크", -6, "링크는 댓글·답글로", "외부 260편: 0.68배(22편) / 우리 120편: 차이 없음");
const numbered = nonEmpty.filter((l) => /^\s*\d[.)]\s/.test(l)).length;
if (numbered >= 3) hit("본문 번호 목록", -6, `번호 목록 ${numbered}줄. 첫 글엔 개수만 말하고 목록은 답글로`, "외부 260편: 0.5배(7편) / 우리 글엔 없음");
if (noSpace < 100) hit("길이", -4, `${noSpace}자. 150~280자가 나았다`, "우리 120편: 151~280자 1.09배 vs 그 밖 0.67배 / 외부 260편: 차이 없음");
else if (noSpace > 480) hit("길이", -25, `${noSpace}자. 쓰레드 한도(500자)에 걸린다`, "플랫폼 한도");
else hit("길이", 0, `${noSpace}자(띄어쓰기 뺌)`, "외부 260편: 길이별 차이 없음");

// ── 자료가 엇갈리거나 차이가 없어 점수에 넣지 않는 것(알림만) ──
const last = nonEmpty[nonEmpty.length - 1] || "";
if (/(\?|너넨|너네는|스친들은|몇 번|어느 쪽|대 봐|골라)\s*$/.test(last)) hit("끝 질문", 0, "질문·투표로 끝남. 자료가 엇갈린다", "우리 120편: 0.78배(61편) / 외부 260편: 1.75배(9편)");
if (/(올트먼|머스크|오픈AI|구글|애플|삼성|네이버|카카오|챗GPT|클로드|제미나이|엔비디아|메타|테슬라|넷플릭스|유튜브|윈도우|아이폰|갤럭시)/.test(first)) hit("아는 이름", 0, "첫 줄에 아는 이름. 이름만으로는 차이가 작았다", "우리 120편: 1.03배 vs 1.06배 / 외부 260편: 1.25배 vs 1.0배");
if (/(^|\s)#[^\s#]+/.test(src)) hit("해시태그", 0, "본문 해시태그. 손해가 확인되지 않았다", "우리 120편·외부 260편 모두 5편씩뿐");
if (/(직장인|취준생|사장님|회사원|신입|대학생|마케터|디자이너|개발자|하는 사람|쓰는 사람|분들)/.test(first) && !mine) hit("대상 부르기", 0, "첫 줄에서 대상을 부른다. 부르는 것만으로는 차이가 없었다", "우리 120편: 0.74배(16편) / 외부 260편: 1.15배(11편)");
// 규칙 점검(성과 근거 없음)
const JARGON = ["프롬프트", "에이전트", "토큰", "API", "MCP", "지시문", "파인튜닝", "벡터", "RAG", "LLM", "오픈소스", "깃허브", "레딧", "해커뉴스", "벤치마크", "파라미터", "컨텍스트", "임베딩", "멀티모달", "하네스", "플러그인", "터미널", "CLI", "워크플로", "온디바이스", "양자화", "가중치", "SDK", "GPU"];
const found = JARGON.filter((w) => text.includes(w)); if (found.length >= 2) hit("낯선 말", -4, `${found.join("·")}. 하나만 남기고 쉬운 말로`, "이해 규칙(성과 근거 없음)");
if (/(월 ?\d+만 ?원|수익|부업|돈 버는)/.test(text)) hit("수익 표현", -10, "수익·부업 표현", "계정 안전 규칙 / 우리 120편: 0.49배(2편)");
if (/[一-鿿]/.test(src)) hit("한자", -30, "한자 금지", "규칙");

score = Math.max(0, Math.min(100, score));
const grade = score >= 85 ? "올려도 됨" : score >= 65 ? "표시된 곳 손보고 올리기" : "다시 쓰기";
console.log(`쓰레드 글 검사  ${score}점 — ${grade}\n`);
for (const r of R) console.log(`${r.pts < 0 ? "▼" : "·"} ${r.name} ${r.pts ? `(${r.pts}) ` : ""}${r.why}\n    근거: ${r.ev}`);
console.log(`\n첫 줄: ${first}`);
console.log(`점수는 우리 쓰레드 120편과 외부 계정 260편에 맞춘 값이에요. 표본이 작아 보장이 아니에요.`);
console.log(JSON.stringify({ score, grade, chars: noSpace, firstLen: fl, lines: nonEmpty.length, firstLine: first, mine, issues: R.filter((r) => r.pts < 0).map((r) => r.name) }));
